#!/bin/bash
# Generate .env.dashboard (password hash + cookie secret).
#
#   bin/dashboard-secrets.sh
#
# The password is read from a hidden prompt and piped in on stdin — never passed as a
# command-line argument. An argument would land in your shell history and be visible in
# `ps` to every user on the box for as long as the command runs.
#
# Run this BEFORE `docker compose up`, since compose needs .env.dashboard to exist.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

OUT="$REPO/.env.dashboard"
IMAGE="etoro-trading-dashboard:latest"

if [[ -f "$OUT" ]]; then
    echo "$OUT already exists."
    read -r -p "Overwrite it? Existing sessions will be invalidated. [y/N] " reply
    [[ "$reply" =~ ^[Yy]$ ]] || { echo "Aborted; nothing changed."; exit 0; }
fi

# Build only if the image is missing — this is also the first build for most people.
if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
    echo "Building $IMAGE (first run only)…"
    docker build -q -t "$IMAGE" "$REPO/dashboard" >/dev/null
fi

echo "Choose a dashboard password (at least 12 characters). Input is hidden."
read -r -s -p "Password: " pw1; echo
read -r -s -p "Confirm:  " pw2; echo

if [[ "$pw1" != "$pw2" ]]; then
    echo "Passwords do not match; nothing written." >&2
    exit 1
fi
if [[ ${#pw1} -lt 12 ]]; then
    echo "Too short: ${#pw1} characters, minimum 12. This will be internet-facing." >&2
    exit 1
fi

# stdin, not argv — see the note at the top.
HASH="$(printf '%s' "$pw1" | docker run --rm -i "$IMAGE" node server/dist/hash-password.js)"
unset pw1 pw2

if [[ ! "$HASH" =~ ^[0-9a-f]{32}:[0-9a-f]{128}$ ]]; then
    echo "Unexpected hash format from the generator; nothing written." >&2
    exit 1
fi

if command -v openssl >/dev/null 2>&1; then
    SECRET="$(openssl rand -hex 32)"
else
    SECRET="$(docker run --rm "$IMAGE" node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")"
fi

umask 077
cat > "$OUT" <<EOF
# Generated by bin/dashboard-secrets.sh on $(date -u +%FT%TZ).
# Gitignored. Values are unquoted on purpose — env_file treats quotes as part of
# the value. Re-run the script to rotate; changing JWT_SECRET logs out every session.
DASHBOARD_PASSWORD_HASH=$HASH
JWT_SECRET=$SECRET
EOF
chmod 600 "$OUT"

echo
echo "Wrote $OUT (mode 600):"
echo "  DASHBOARD_PASSWORD_HASH  ${HASH:0:12}…  (scrypt saltHex:hashHex)"
echo "  JWT_SECRET               ${SECRET:0:8}…  (32 random bytes)"
echo
echo "Next: docker compose up -d"
